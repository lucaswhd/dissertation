#!/usr/bin/env python3
"""Visualize the OmniGibson traversability map that the HRC nav code (A*) actually uses.

The map is NOT generated by our code: A* runs on `scene.trav_map.floor_map[floor]`,
which OmniGibson loads from the scene's `layout/floor_trav_{floor}.png`
(when trav_map_with_objects=True, the default) and downsizes to map_resolution.

  white (255) / value > 0  -> traversable
  black (0)   / value == 0  -> obstacle (wall OR furniture)

This script renders, with world-coordinate (metre) axes:
  1) <tag>_navmap.png    -- the actual nav map A* sees (with objects), cropped to the house.
  2) <tag>_furniture.png -- composite: walls (dark) vs furniture footprint (orange) vs free.
                            furniture = free in floor_trav_no_obj but blocked in floor_trav.

No simulator / GPU needed -- reads the same PNGs OmniGibson would load.

Usage:
  python viz_trav_map.py \
      --scene-layout /root/autodl-tmp/datasets/behavior-1k-assets/scenes/house_double_floor_lower/layout \
      --floor 0 \
      --out /root/autodl-tmp/hrc_pipeline_traintest/outputs/trav_map_viz
"""
import argparse
import os

import numpy as np
from PIL import Image
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Patch

# OmniGibson dataset convention (see omnigibson/maps/traversable_map.py)
NATIVE_RES_M = 0.01      # each pixel in floor_trav_*.png == 1 cm
RUNTIME_RES_M = 0.1      # default map_resolution -> floor_map[0] is ~1/10 the size


def _load(path):
    return np.asarray(Image.open(path).convert("L"))


def _crop_bbox(free_mask, margin_px):
    rows = np.where(free_mask.any(axis=1))[0]
    cols = np.where(free_mask.any(axis=0))[0]
    r0, r1 = rows.min(), rows.max()
    c0, c1 = cols.min(), cols.max()
    H, W = free_mask.shape
    r0 = max(0, r0 - margin_px); r1 = min(H - 1, r1 + margin_px)
    c0 = max(0, c0 - margin_px); c1 = min(W - 1, c1 + margin_px)
    return r0, r1, c0, c1


def _extent(r0, r1, c0, c1, H, W):
    # world_x = (col - W/2)*res ; world_y = (row - H/2)*res   (row<->y, col<->x)
    x_left = (c0 - W / 2.0) * NATIVE_RES_M
    x_right = (c1 + 1 - W / 2.0) * NATIVE_RES_M
    y_bottom = (r0 - H / 2.0) * NATIVE_RES_M
    y_top = (r1 + 1 - H / 2.0) * NATIVE_RES_M
    return (x_left, x_right, y_bottom, y_top)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scene-layout", required=True,
                    help="Path to <scene>/layout dir containing floor_trav_*.png")
    ap.add_argument("--floor", type=int, default=0)
    ap.add_argument("--out", required=True, help="Output dir for PNGs")
    ap.add_argument("--tag", default=None, help="Filename tag (default: scene name)")
    ap.add_argument("--margin-m", type=float, default=1.0, help="Crop margin in metres")
    args = ap.parse_args()

    layout = args.scene_layout
    floor = args.floor
    os.makedirs(args.out, exist_ok=True)
    tag = args.tag or os.path.basename(os.path.dirname(os.path.normpath(layout)))

    p_obj = os.path.join(layout, f"floor_trav_{floor}.png")
    p_noobj = os.path.join(layout, f"floor_trav_no_obj_{floor}.png")
    trav = _load(p_obj)                       # what A* uses (with objects)
    H, W = trav.shape
    free = trav > 0                           # matches code: int(fmap[i,j]) > 0

    has_noobj = os.path.exists(p_noobj)
    noobj = _load(p_noobj) if has_noobj else None

    margin_px = int(round(args.margin_m / NATIVE_RES_M))
    # crop to the structural interior (no_obj is the widest free region) if available
    crop_src = (noobj > 0) if has_noobj else free
    r0, r1, c0, c1 = _crop_bbox(crop_src, margin_px)
    extent = _extent(r0, r1, c0, c1, H, W)

    free_c = free[r0:r1 + 1, c0:c1 + 1]

    # ---------- Figure 1: nav map A* actually uses ----------
    fig, ax = plt.subplots(figsize=(10, 10))
    ax.imshow(free_c, origin="lower", extent=extent, cmap="gray",
              interpolation="nearest", vmin=0, vmax=1)
    ax.set_title(f"{tag}  floor {floor}  --  nav map A* uses (floor_trav_{floor}.png)\n"
                 f"white = traversable   black = obstacle (wall or furniture)")
    ax.set_xlabel("world X (m)"); ax.set_ylabel("world Y (m)")
    ax.axhline(0, color="cyan", lw=0.6, alpha=0.6)
    ax.axvline(0, color="cyan", lw=0.6, alpha=0.6)
    ax.grid(True, color="dodgerblue", lw=0.3, alpha=0.4)
    out1 = os.path.join(args.out, f"{tag}_floor{floor}_navmap.png")
    fig.tight_layout(); fig.savefig(out1, dpi=130); plt.close(fig)

    free_pct = 100.0 * free_c.mean()
    print(f"[viz] {out1}")
    print(f"      native shape={trav.shape} (res {NATIVE_RES_M} m/px) "
          f"-> runtime floor_map ~{int(H*NATIVE_RES_M/RUNTIME_RES_M)}px (res {RUNTIME_RES_M} m/px)")
    print(f"      world extent X[{extent[0]:.2f},{extent[1]:.2f}] "
          f"Y[{extent[2]:.2f},{extent[3]:.2f}] m ; free in crop = {free_pct:.1f}%")

    # ---------- Figure 2: furniture footprint composite ----------
    if has_noobj:
        noobj_free = noobj > 0
        # categories on the crop:
        #   2 free (traversable)      -> light
        #   1 furniture footprint     -> orange  (free w/o objects, blocked with objects)
        #   0 wall / structure        -> dark gray
        cat = np.zeros_like(free, dtype=np.uint8)
        cat[noobj_free] = 1            # interior reachable ignoring furniture
        cat[free] = 2                  # actually traversable now
        # cells that are interior(1) but not traversable(2) stay 1 = furniture
        cat_c = cat[r0:r1 + 1, c0:c1 + 1]

        rgb = np.empty(cat_c.shape + (3,), dtype=np.uint8)
        rgb[cat_c == 0] = (60, 60, 65)       # walls / structure / outside
        rgb[cat_c == 1] = (240, 130, 30)     # furniture footprint A* avoids
        rgb[cat_c == 2] = (235, 235, 235)    # free / traversable

        fig, ax = plt.subplots(figsize=(10, 10))
        ax.imshow(rgb, origin="lower", extent=extent, interpolation="nearest")
        ax.set_title(f"{tag}  floor {floor}  --  what blocks navigation\n"
                     f"orange = furniture/object footprint   dark = wall/structure   light = free")
        ax.set_xlabel("world X (m)"); ax.set_ylabel("world Y (m)")
        ax.axhline(0, color="cyan", lw=0.6, alpha=0.6)
        ax.axvline(0, color="cyan", lw=0.6, alpha=0.6)
        ax.grid(True, color="dodgerblue", lw=0.3, alpha=0.4)
        ax.legend(handles=[
            Patch(color=(235/255, 235/255, 235/255), label="traversable"),
            Patch(color=(240/255, 130/255, 30/255), label="furniture footprint (A* avoids)"),
            Patch(color=(60/255, 60/255, 65/255), label="wall / structure"),
        ], loc="upper right", fontsize=8)
        out2 = os.path.join(args.out, f"{tag}_floor{floor}_furniture.png")
        fig.tight_layout(); fig.savefig(out2, dpi=130); plt.close(fig)
        furn_pct = 100.0 * (cat_c == 1).mean()
        print(f"[viz] {out2}")
        print(f"      furniture footprint = {furn_pct:.1f}% of crop "
              f"(blocked-by-object cells; these are what A*/deflect must route around)")
    else:
        print(f"[viz] floor_trav_no_obj_{floor}.png not found -> skipped furniture composite")


if __name__ == "__main__":
    main()
